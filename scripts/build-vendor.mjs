#!/usr/bin/env node
/**
 * Empaqueta las librerías de scripts/vendor-manifest.mjs en IIFE versionados en js/vendor/,
 * copia sus licencias a licenses/ y regenera THIRD_PARTY_NOTICES.md.
 *
 * Uso: node scripts/build-vendor.mjs [--out-dir <dir>]
 * `--out-dir` escribe los artefactos en otro directorio (por defecto, la raíz del repositorio).
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { VENDORS } from './vendor-manifest.mjs';

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXACT_VERSION = /^\d+\.\d+\.\d+$/;
const requireFromRoot = createRequire(path.join(ROOT_DIR, 'package.json'));

function parseOutDir(argv) {
  const index = argv.indexOf('--out-dir');
  if (index === -1) return ROOT_DIR;
  const value = argv[index + 1];
  if (!value) throw new Error('--out-dir requires a directory');
  return path.resolve(value);
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function packageDir(name) {
  return path.dirname(requireFromRoot.resolve(`${name}/package.json`));
}

/** Comprueba que la dependencia está fijada a una versión exacta e instalada en esa versión. */
function resolvePinnedVersion(vendor, dependencies) {
  const pinned = dependencies[vendor.package];
  if (!pinned) throw new Error(`${vendor.package} is not listed in package.json dependencies`);
  if (!EXACT_VERSION.test(pinned)) throw new Error(`${vendor.package} must be pinned to an exact version, found "${pinned}"`);
  const installed = readJson(path.join(packageDir(vendor.package), 'package.json')).version;
  if (installed !== pinned) throw new Error(`${vendor.package} ${installed} is installed but package.json pins ${pinned}; run npm ci`);
  return pinned;
}

function entryContents(vendor) {
  if (vendor.exports === '*') return `export * from '${vendor.package}';`;
  return `export { ${vendor.exports.join(', ')} } from '${vendor.package}';`;
}

function licenseOutfile(vendor) {
  return `licenses/${vendor.id.toUpperCase()}-LICENSE.md`;
}

function noticesText(entries) {
  const lines = [
    '# Third-party notices',
    '',
    'ZeroChat embeds the following dependencies in its standalone distribution.',
    'This file is generated by `npm run build:vendor` from `scripts/vendor-manifest.mjs`.',
    ''
  ];
  for (const { vendor, version } of entries) {
    lines.push(
      `- \`${vendor.package}\` ${version} — ${vendor.license.copyright} — ${vendor.license.name}.`,
      `  Source: ${vendor.source}`,
      `  License: [${licenseOutfile(vendor)}](${licenseOutfile(vendor)})`,
      `  Bundle: \`${vendor.outfile}\` (global \`${vendor.globalName}\`${vendor.onDemand ? ', loaded on demand' : ''})`
    );
  }
  lines.push('', 'The dependencies are bundled without modification beyond minification and module-format conversion.', '');
  return lines.join('\n');
}

async function buildVendor(vendor, outDir) {
  const outfile = path.join(outDir, vendor.outfile);
  await build({
    stdin: { contents: entryContents(vendor), resolveDir: ROOT_DIR, loader: 'js' },
    outfile,
    bundle: true,
    format: 'iife',
    globalName: vendor.globalName,
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    logLevel: 'warning'
  });
  const licenseSource = path.join(packageDir(vendor.package), vendor.license.file);
  const licenseTarget = path.join(outDir, licenseOutfile(vendor));
  fs.mkdirSync(path.dirname(licenseTarget), { recursive: true });
  fs.copyFileSync(licenseSource, licenseTarget);
  return fs.statSync(outfile).size;
}

async function main() {
  const outDir = parseOutDir(process.argv.slice(2));
  const { dependencies = {} } = readJson(path.join(ROOT_DIR, 'package.json'));
  const entries = VENDORS.map(vendor => ({ vendor, version: resolvePinnedVersion(vendor, dependencies) }));
  for (const entry of entries) {
    const size = await buildVendor(entry.vendor, outDir);
    console.log(`${entry.vendor.package}@${entry.version} -> ${entry.vendor.outfile} (${Math.round(size / 1024)} KiB)`);
  }
  fs.writeFileSync(path.join(outDir, 'THIRD_PARTY_NOTICES.md'), noticesText(entries));
}

main().catch(error => {
  console.error(error.message);
  process.exit(1);
});
